/**
 * LaTeX 补全的静态命令 / 环境 / snippet 表。
 *
 * **数据来源**：LaTeX-Workshop（MIT，Copyright (c) 2016 James Yu）的
 * `data/commands.json`、`data/macros.json`、`data/environments.json`、
 * `data/latex-snippet.json`，只取 name / snippet / detail / documentation。许可声明见
 * 仓根 `NOTICE`；转换是 2026-10-28 的一次性脚本（VS Code snippet 语法 → CodeMirror 的
 * `snippet()`：`${TM_SELECTED_TEXT}` → `${1}`，`$N` → `${N}`，字面花括号写成 `\\{`）。
 *
 * **不引 TeXStudio 的 cwl 包数据**：那是 5.3 MB / 247 个文件，许可不明确（TeXStudio 是
 * GPL，cwl 由 LaTeX-Workshop 以 MIT 二次分发），本期只做「默认命令 + 项目运行时索引」
 * （主进程 `src/main/latex/index.ts`）。需要包级命令时再单独核许可。
 *
 * 静态表只回答「打了 \fra 该给什么」；项目里自己定义的命令 / 环境由运行时索引补，
 * 两者在 latex-suggest.ts 里合并（同名以静态表的 snippet 为准，运行时只补名字）。
 */
export interface LatexCommandData {
  name: string;
  /** CodeMirror snippet 语法（字段是 `${1:...}`），**不含**前导反斜杠 */
  snippet: string;
  /** 候选行右侧的一句话（`frac` → "fraction"） */
  detail: string;
  /** 选中时才显示的补充说明（参数签名 / 用途），没有时 null */
  doc: string | null;
}

export interface LatexEnvironmentData {
  name: string;
  /** `\begin{env}` 之后要插入的内容（含 body 的 `\n\t` 与 `${0}`） */
  snippet: string;
  /** 参数形状（`\begin{array}{cols}`）；没有参数时 null */
  detail: string | null;
}

export interface LatexSnippetData {
  prefix: string;
  body: string;
  description: string;
}

