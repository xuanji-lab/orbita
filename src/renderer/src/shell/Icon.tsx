export type IconName = keyof typeof ICONS;

/**
 * SVG 源文件里的换行与缩进会原样变成 DOM 文本节点，把承载图标的按钮的 `textContent`
 * 污染成 `"\n  \n  \nProviders"`——读屏与任何按文本找元素的东西都会踩到。
 * 构建期洗一次，运行时零成本。
 */
function inline(svg: string): string {
  return svg.trim().replace(/>\s+</g, "><");
}

/**
 * 尺寸与描边由外层 span 控制：`.orbita-icon svg` 用 CSS 覆盖 SVG 的呈现属性
 * （CSS 优先级高于 presentation attribute），所以不必改写 SVG 源串。
 * 图标继承 `currentColor`——颜色一律由父级的 color 决定。
 */
export function Icon(props: {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  spin?: boolean;
  /**
   * 填实图标（用 currentColor 填内部）。lucide 是线性图标集，描边与填实在这里是
   * **同一个图标的两种状态**（未星标 / 已星标），而不是两个图标——
   * 用 `star` / `star-off` 表达开关会把「已星标」画成一个带斜杠的禁止符。
   * 填色走 CSS 变量（同 `--icon-stroke`），不改写 SVG 源串。
   *
   * 今天唯一的消费者是星标，而 star 是**单一形状**，填实一路继承下去就是对的。
   * （多形状图标如 circle-check 还需要一个内部标记色才不至于把勾吃掉，等真有那么
   * 一个消费者时再加——没有调用点的代码不留在分支里。）
   */
  fill?: boolean;
  style?: React.CSSProperties;
  /**
   * 调用方追加的 class（如 MCP 面板自己的 mcp-spin：那两处不是 `spin` 支持的
   * orbita-spin 动画，仍要挂 anim-continuous 才能被窗口失焦时暂停）。
   */
  className?: string;
}) {
  const size = props.size ?? 16;
  const style = {
    width: size,
    height: size,
    "--icon-stroke": props.strokeWidth ?? 2,
    ...(props.fill === true
      ? { "--icon-fill": "currentColor" }
      : null),
    ...(props.spin === true ? { animation: "orbita-spin 1s linear infinite" } : null),
    ...props.style,
  } as React.CSSProperties;
  // spin 是持续动效（orbita-spin infinite）：anim-continuous 标记它，好让窗口
  // 失焦时 styles.css 能把它暂停（不用全局 `*`，见那条规则的注释）
  const classes = ["orbita-icon", props.spin === true ? "anim-continuous" : null, props.className]
    .filter((value) => value !== null && value !== undefined)
    .join(" ");
  return (
    <span
      className={classes}
      aria-hidden="true"
      style={style}
      // iconMarkup 按图标名缓存同一个 { __html } 对象：字面量在每次渲染新建对象，
      // React 19 按对象身份（不是字符串内容）判断要不要重写 innerHTML，流式时
      // 每个增量都会重渲染侧栏 / 右图标条，字面量写法会让整棵 SVG 每次都被拆了
      // 重建——用户点在图标上时 pointerdown 落的节点在松手前已经被摘掉，浏览器
      // 收不到 click（详见 icon-markup.ts 顶部注释）。
      dangerouslySetInnerHTML={iconMarkup(props.name, () => inline(ICONS[props.name]))}
    />
  );
}
